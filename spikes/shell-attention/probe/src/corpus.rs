//! The programs measured, each typed into the tab's shell as a user would.
//! `expect` is whether the command is waiting on the user at the terminal:
//! the label a rule is scored against.

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Os {
    Both,
    Linux,
    Macos,
}

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Prep {
    None,
    Http401,
    Stall,
    Sshd,
    Fifo,
    BigFile,
    BigC,
    Notes,
}

pub struct Case {
    pub id: &'static str,
    pub cat: &'static str,
    pub expect: bool,
    pub cmd: &'static str,
    pub needs: &'static [&'static str],
    pub os: Os,
    pub prep: Prep,
}

const fn c(
    id: &'static str,
    cat: &'static str,
    expect: bool,
    cmd: &'static str,
    needs: &'static [&'static str],
    os: Os,
    prep: Prep,
) -> Case {
    Case {
        id,
        cat,
        expect,
        cmd,
        needs,
        os,
        prep,
    }
}

